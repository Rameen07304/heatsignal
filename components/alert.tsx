export const LANGS = [
  { key: "en", label: "English", dir: "ltr", lang: "en", headings: ["Risk assessment", "Who is at risk", "Recommended actions", "Worker safety"] },
  { key: "ur", label: "اردو", dir: "rtl", lang: "ur", headings: ["خطرے کا جائزہ", "کون زیادہ خطرے میں ہے", "تجویز کردہ اقدامات", "مزدوروں کی حفاظت"] },
  { key: "ar", label: "العربية", dir: "rtl", lang: "ar", headings: ["تقييم الخطر", "الفئات الأكثر عرضة", "الإجراءات الموصى بها", "سلامة العمال"] },
] as const;

export function AlertBody({ text, headings, dir, lang }: { text: AlertText; headings: readonly string[]; dir: string; lang: string }) {
  const lists: [string, string[]][] = [
    [headings[1], text.vulnerable_groups],
    [headings[2], text.actions],
    [headings[3], text.worker_safety],
  ];
  return (
    <div dir={dir} lang={lang} className="space-y-4 text-sm leading-relaxed">
      <section>
        <h4 className="mb-1 font-semibold">{headings[0]}</h4>
        <p>{text.risk_assessment}</p>
      </section>
      {lists.map(([h, items]) =>
        items.length ? (
          <section key={h}>
            <h4 className="mb-1 font-semibold">{h}</h4>
            <ul className="list-disc space-y-0.5 ps-5">
              {items.map((x, i) => <li key={i}>{x}</li>)}
            </ul>
          </section>
        ) : null,
      )}
    </div>
  );
}

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);

/** Opens the alert as a clean printable page; the browser's print dialog offers "Save as PDF". */
function printAlert(title: string, subtitle: string, alert: HeatAlert) {
  const win = window.open("", "_blank", "width=800,height=900");
  if (!win) return;
  const blocks = LANGS.map((l) => {
    const t = alert[l.key];
    if (!t) return "";
    const list = (h: string, xs: string[]) => (xs.length ? `<h3>${esc(h)}</h3><ul>${xs.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>` : "");
    return `<section dir="${l.dir}" lang="${l.lang}"><h2>${esc(l.label)}</h2><h3>${esc(l.headings[0])}</h3><p>${esc(t.risk_assessment)}</p>${list(l.headings[1], t.vulnerable_groups)}${list(l.headings[2], t.actions)}${list(l.headings[3], t.worker_safety)}</section>`;
  }).join("");
  win.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title><style>
    body{font-family:system-ui,-apple-system,"Segoe UI",sans-serif;max-width:720px;margin:32px auto;padding:0 24px;color:#111;line-height:1.5}
    h1{font-size:22px;margin:0}.sub{color:#555;margin:4px 0 24px}h2{font-size:16px;border-bottom:2px solid #ef4444;padding-bottom:4px;margin-top:28px}
    h3{font-size:13px;margin:14px 0 4px}p,li{font-size:13px}section{page-break-inside:avoid}footer{margin-top:32px;font-size:11px;color:#666}
  </style></head><body><h1>${esc(title)}</h1><p class="sub">${esc(subtitle)}</p>${blocks}
  <footer>Generated by HeatSignal on ${esc(new Date().toLocaleString())}. ${alert.source === "ai" ? "AI-written — review before public distribution." : "Standard guidance (AI unavailable)."}</footer></body></html>`);
  win.document.close();
  win.focus();
  win.print();
}

export function AlertView({ alert, note, title, subtitle }: { alert: HeatAlert; note?: string; title: string; subtitle: string }) {
  const [copied, setCopied] = useState(false);
  return (
    <div className="space-y-3">
      {note && (
        <p className="rounded-md border border-yellow-500/40 bg-yellow-500/10 p-2 text-xs">{note}</p>
      )}
      <Tabs defaultValue="en">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <TabsList>
            {LANGS.map((l) => (
              <TabsTrigger key={l.key} value={l.key} disabled={!alert[l.key]}>{l.label}</TabsTrigger>
            ))}
          </TabsList>
          <div className="flex gap-2">
            <Button
              size="sm"
              variant="outline"
              onClick={async () => {
                try {
                  await navigator.clipboard.writeText(alertToText(`${title} — ${subtitle}`, alert));
                  setCopied(true);
                  setTimeout(() => setCopied(false), 2000);
                } catch {}
              }}
            >
              {copied ? <Check /> : <Copy />} {copied ? "Copied" : "Copy alert"}
            </Button>
            <Button size="sm" variant="outline" onClick={() => printAlert(title, subtitle, alert)}>
              <FileDown /> Download as PDF
            </Button>
          </div>
        </div>
        {LANGS.map((l) => {
          const t = alert[l.key];
          return t ? (
            <TabsContent key={l.key} value={l.key}>
              <AlertBody text={t} headings={l.headings} dir={l.dir} lang={l.lang} />
            </TabsContent>
          ) : null;
        })}
      </Tabs>
      {alert.source === "ai" && (
        <p className="text-xs text-muted-foreground">AI-generated by Gemini from the measured values above. Review before sharing publicly.</p>
      )}
    </div>
  );
}

/** Generate a one-shot alert for a city's current hour and record it in the alert history. */
export function useAlert(city: City, hour: CombinedHour) {
  const [alert, setAlert] = useState<HeatAlert | null>(null);
  const [note, setNote] = useState<string>();
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  async function generate() {
    setLoading(true);
    setError(null);
    setAlert(null);
    try {
      const res = await postAlert<HeatAlert & { note?: string }>(alertBody(city, hour));
      const { note: n, ...a } = res;
      setAlert(a);
      setNote(n ?? (a.source === "ai" && (!a.ur || !a.ar) ? "A translation was not available this time; try again for Urdu and Arabic." : undefined));
      saveToHistory(city, hour, a, "single");
    } catch (e) {
      setError(e instanceof Error ? e.message : "Something went wrong");
    } finally {
      setLoading(false);
    }
  }
  return { alert, note, error, loading, generate };
}

function summary(hour: CombinedHour) {
  return [
    `WBGT ${hour.wbgt.toFixed(1)} °C (${hour.risk})`,
    `${hour.temp.toFixed(1)} °C`,
    `${hour.rh.toFixed(0)}% humidity`,
    hour.air && `AQI ${formatAqi(hour.air.aqi)}`,
    hour.air && `UV ${hour.air.uv.toFixed(0)}`,
  ].filter(Boolean).join(" · ");
}

function AlertState({ state, city, hour }: { state: ReturnType<typeof useAlert>; city: City; hour: CombinedHour }) {
  return (
    <>
      {state.loading && (
        <div className="flex items-center gap-2 py-8 text-sm text-muted-foreground" role="status">
          <Loader2 className="h-4 w-4 animate-spin" /> Generating alert in English, Urdu and Arabic…
        </div>
      )}
      {state.error && (
        <div role="alert" className="space-y-3 rounded-md border border-destructive/50 bg-destructive/10 p-4 text-sm">
          <p className="flex items-start gap-2">
            <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-destructive" /> {state.error}
          </p>
          <Button size="sm" variant="outline" onClick={state.generate}>Try again</Button>
        </div>
      )}
      {state.alert && (
        <AlertView alert={state.alert} note={state.note} title={`Health alert — ${city.name}`} subtitle={summary(hour)} />
      )}
    </>
  );
}

export function AlertDialog({ city, hour, label = "Generate Alert", ...buttonProps }: { city: City; hour: CombinedHour; label?: string } & ButtonProps) {
  const state = useAlert(city, hour);
  return (
    <Dialog onOpenChange={(open) => open && !state.alert && !state.loading && state.generate()}>
      <DialogTrigger asChild>
        <Button {...buttonProps}>
          <Siren /> {label}
        </Button>
      </DialogTrigger>
      <DialogContent className="max-w-2xl">
        <DialogHeader>
          <DialogTitle className="flex flex-wrap items-center gap-2">
            Health alert — {city.name} {hour.score != null && <CompoundBadge score={hour.score} />}
          </DialogTitle>
          <DialogDescription>{summary(hour)}</DialogDescription>
        </DialogHeader>
        <AlertState state={state} city={city} hour={hour} />
      </DialogContent>
    </Dialog>
  );
}

/** Inline version for the city page. */
export function AlertSection({ city, hour }: { city: City; hour: CombinedHour }) {
  const state = useAlert(city, hour);
  return (
    <Card>
      <CardHeader className="flex-row flex-wrap items-start justify-between gap-3 space-y-0">
        <div>
          <CardTitle>AI health alert</CardTitle>
          <CardDescription>
            A plain-language warning written from this hour’s numbers, in English, Urdu and Arabic.
          </CardDescription>
        </div>
        <Button onClick={state.generate} disabled={state.loading}>
          <Siren /> {state.alert ? "Regenerate" : "Generate Detailed Alert"}
        </Button>
      </CardHeader>
      {(state.loading || state.error || state.alert) && (
        <CardContent>
          <AlertState state={state} city={city} hour={hour} />
        </CardContent>
      )}
    </Card>
  );
}

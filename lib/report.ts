/**
 * Opens a clean black-on-white page in a new window and starts printing; the print dialog offers
 * "Save as PDF". All text passed in `body` must already be escaped.
 */
export function openPrintable(title: string, subtitle: string, body: string) {
  const win = window.open("", "_blank", "width=860,height=1000");
  if (!win) return alert("Your browser blocked the report window. Allow pop-ups for this site and try again.");
  win.document.write(
    `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title><style>${CSS}</style></head><body>` +
      `<header>${LOGO}<h1>${esc(title)}</h1></header><p class="sub">${esc(subtitle)}</p>${body}` +
      `<footer>Report generated by HeatSignal — ${esc(location.origin)} · Data: Open-Meteo.com (CC BY 4.0; air quality from Copernicus CAMS) · Thresholds: WHO, NIOSH, ACGIH/OSHA, US EPA, ISO 7243. Decision support, not medical advice.</footer>` +
      `</body></html>`,
  );
  win.document.close();
  win.focus();
  win.print();
}

const list = (xs: string[]) => `<ul>${xs.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>`;
const row = (cells: (string | number)[], th = false) =>
  `<tr>${cells.map((c) => (th ? `<th>${esc(String(c))}</th>` : `<td>${esc(String(c))}</td>`)).join("")}</tr>`;

/** Single-city report: conditions, 7-day forecast, groups at risk, advisory and actions. */
export function cityReport(
  city: City,
  c: Conditions,
  groups: { name: string; advice: string }[],
  advisory: { text: AlertText; source: "ai" | "rules" },
) {
  const n = c.now;
  const a = n.air;
  const body = `
<section><h2>Current conditions</h2>
<p>Temperature: ${n.temp.toFixed(1)} °C | Humidity: ${n.rh.toFixed(0)}% | Wind: ${n.wind.toFixed(0)} km/h</p>
<p>WBGT (heat stress): <b>${n.wbgt.toFixed(1)} °C — ${esc(n.risk)}</b></p>
${a ? `<p>Air quality (US AQI): <b>${formatAqi(a.aqi)} — ${esc(aqiBand(a.aqi).label)}</b></p>
<p>PM2.5: ${a.pm25.toFixed(0)} µg/m³ | Ozone: ${a.o3.toFixed(0)} µg/m³ | NO₂: ${a.no2.toFixed(0)} µg/m³</p>
<p>UV index: ${a.uv.toFixed(0)} — ${esc(uvBand(a.uv).label)}</p>` : "<p>Air quality: no data for this location.</p>"}
${n.score != null ? `<p class="big">Compound risk score: ${n.score}/100 — ${esc(compoundBand(n.score).level)}</p>` : ""}
</section>
<section><h2>7-day forecast</h2><table>
${row(["Date", "Max temp", "Max WBGT", "Heat risk", "Max AQI", "Air risk", "Compound", "Overall"], true)}
${c.days
  .map((d) =>
    row([
      formatDay(d.date),
      `${d.maxTemp.toFixed(1)} °C`,
      `${d.maxWbgt.toFixed(1)} °C`,
      d.risk,
      d.maxAqi != null ? formatAqi(d.maxAqi) : "–",
      d.maxAqi != null ? aqiBand(d.maxAqi).label : "–",
      d.maxScore ?? "–",
      d.level ?? "–",
    ]),
  )
  .join("")}
</table><p class="sub">Air-quality forecasts reach about 5 days ahead.</p></section>
<section><h2>Vulnerable populations at risk</h2>
${groups.length ? `<ul>${groups.map((g) => `<li><b>${esc(g.name)}</b> — ${esc(g.advice)}</li>`).join("")}</ul>` : "<p>No group needs special precautions today.</p>"}
</section>
<section><h2>${advisory.source === "ai" ? "AI-generated advisory" : "Advisory"}</h2>
<p>${esc(advisory.text.risk_assessment)}</p><h3>Who is at risk</h3>${list(advisory.text.vulnerable_groups)}
${advisory.text.worker_safety.length ? `<h3>Worker safety</h3>${list(advisory.text.worker_safety)}` : ""}</section>
<section><h2>Recommended actions</h2>${list(advisory.text.actions)}</section>`;
  openPrintable(
    `HeatSignal Environmental Health Report — ${city.name}`,
    `${[city.name, city.country].filter(Boolean).join(", ")} · Generated ${new Date().toLocaleString()} · Local time at city ${formatDay(n.time)} ${n.time.slice(11, 16)}`,
    body,
  );
}

/** Global summary report for every monitored city. */
export function globalReport(rows: { city: City; c: Conditions }[]) {
  const ranked = [...rows].sort((a, b) => (b.c.days[0].maxScore ?? -1) - (a.c.days[0].maxScore ?? -1));
  const count = (f: (r: (typeof rows)[number]) => boolean) => rows.filter(f).length;
  const body = `
<section><h2>Summary</h2>
<p>Cities monitored: <b>${rows.length}</b></p>
<p>Critical or worse compound risk today (score ≥ 76): <b>${count((r) => (r.c.days[0].maxScore ?? 0) >= 76)}</b></p>
<p>High or Extreme heat stress today: <b>${count((r) => r.c.days[0].risk === "High" || r.c.days[0].risk === "Extreme")}</b></p>
<p>Unhealthy air now (AQI > 150): <b>${count((r) => (r.c.now.air?.aqi ?? 0) > 150)}</b></p></section>
<section><h2>Cities ranked by today’s peak compound risk</h2><table>
${row(["#", "City", "Country", "Peak WBGT", "Heat", "AQI now", "Compound", "Level"], true)}
${ranked
  .map((r, i) =>
    row([
      i + 1,
      r.city.name,
      r.city.country,
      `${r.c.days[0].maxWbgt.toFixed(1)} °C`,
      r.c.days[0].risk,
      r.c.now.air ? formatAqi(r.c.now.air.aqi) : "–",
      r.c.days[0].maxScore ?? "–",
      r.c.days[0].level ?? "–",
    ]),
  )
  .join("")}
</table></section>`;
  openPrintable("HeatSignal Global Environmental Health Summary", `Generated ${new Date().toLocaleString()}`, body);
}
